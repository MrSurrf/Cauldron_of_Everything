import { describe, expect, it } from 'vitest'
import { matchSpellFrequencyLabel } from './creatureSectionPresentation'

describe('метки списков заклинаний существа', () => {
  it.each([
    ['Неограниченно: свет', 'Неограниченно'],
    ['По желанию: обнаружение магии', 'По желанию'],
    ['Постоянно: невидимость', 'Постоянно'],
    ['1 раз в день: телепортация', '1 раз в день'],
    ['3/день каждое: огненный шар, полёт', '3/день каждое'],
    ['По 3 раза в день: полёт', 'По 3 раза в день'],
    ['1/день (каждое): полёт', '1/день (каждое)'],
    ['Заговоры (неограниченно): свет', 'Заговоры (неограниченно)'],
    ['1-й уровень (4 ячейки): щит', '1-й уровень (4 ячейки)'],
    ['1–2-й уровень (3 ячейки 2-го уровня): щит', '1–2-й уровень (3 ячейки 2-го уровня)'],
  ])('сохраняет частоту и уточнения: %s', (text, label) => {
    const match = matchSpellFrequencyLabel(text)
    expect(match?.label).toBe(label)
    expect(text.slice(match?.prefixLength)).not.toMatch(/^\s*:/)
  })

  it.each([
    'Неограниченно использует способность.',
    'Использование заклинаний. Маг использует следующие заклинания:',
    'Легендарное сопротивление (3/день).',
    '1-й уровень опасности: описание',
    'Лидерство (перезаряжается после отдыха).',
  ])('оставляет обычный текст без преобразования: %s', (text) => {
    expect(matchSpellFrequencyLabel(text)).toBeUndefined()
  })
})
